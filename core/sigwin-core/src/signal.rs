//! presage integration: open the encrypted store, link as a secondary device,
//! request the contacts sync, enumerate conversations, stream live messages, and
//! send messages via a command channel.
//!
//! Receiving and sending each need `&mut Manager`, so we run them on two cheap
//! `Manager` clones concurrently in one task (the receive stream is not `Send`,
//! so we don't spawn it onto another thread).

