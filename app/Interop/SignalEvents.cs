using System;
using System.Collections.Generic;
using System.Text.Json;

namespace signal_windows_client.Interop;

/// <summary>Attachment on a message. Small images/videos carry their decrypted
/// bytes inline (<see cref="DataBase64"/>); larger/other files are metadata-only.</summary>
public sealed class AttachmentDto
{
    public string? ContentType { get; set; }
    public uint? Size { get; set; }
    public string? FileName { get; set; }
    public string? DataBase64 { get; set; }
}

/// <summary>The message being replied to, flattened for display.</summary>
public sealed class QuoteDto
{
    public long Timestamp { get; set; }
    public string Author { get; set; } = "";
    public string? Text { get; set; }
}

/// <summary>A link preview card (generated by the sender's own client).</summary>
public sealed class PreviewDto
{
    public string Url { get; set; } = "";
    public string? Title { get; set; }
    public string? Description { get; set; }
    public string? ImageBase64 { get; set; }
}

/// <summary>A message delivered from the Rust core.</summary>
public sealed class IncomingMessageDto
{
    public string ThreadId { get; set; } = "";
    public string Sender { get; set; } = "";
    public long Timestamp { get; set; }
    public string? Body { get; set; }
    public List<AttachmentDto> Attachments { get; set; } = new();
    public bool Group { get; set; }
    public bool IsOutgoing { get; set; }
    public bool Historical { get; set; }
    public bool IsViewOnce { get; set; }
    public QuoteDto? Quote { get; set; }
    public PreviewDto? Preview { get; set; }
}

/// <summary>A conversation (sidebar entry) discovered in the store.</summary>
public sealed class ConversationDto
{
    public string ThreadId { get; set; } = "";
    public string Title { get; set; } = "";
    public string? LastBody { get; set; }
    public long LastTimestamp { get; set; }
    public bool IsGroup { get; set; }
}

/// <summary>Strongly-typed form of the core's internally-tagged JSON events.</summary>
public abstract record SignalEvent
{
    private static readonly JsonSerializerOptions Options = new()
    {
        PropertyNamingPolicy = JsonNamingPolicy.SnakeCaseLower,
        PropertyNameCaseInsensitive = true,
    };

    public static SignalEvent Parse(string json)
    {
        try
        {
            using var doc = JsonDocument.Parse(json);
            var type = doc.RootElement.TryGetProperty("type", out var t) ? t.GetString() : null;
            string Str(string prop) => doc.RootElement.TryGetProperty(prop, out var v) ? v.GetString() ?? "" : "";
            long Long(string prop) => doc.RootElement.TryGetProperty(prop, out var v) ? v.GetInt64() : 0;
            bool Bool(string prop) => doc.RootElement.TryGetProperty(prop, out var v) && v.GetBoolean();
            string? StrOrNull(string prop) =>
                doc.RootElement.TryGetProperty(prop, out var v) && v.ValueKind != JsonValueKind.Null ? v.GetString() : null;
            List<long> LongArray(string prop)
            {
                var list = new List<long>();
                if (doc.RootElement.TryGetProperty(prop, out var arr) && arr.ValueKind == JsonValueKind.Array)
                    foreach (var el in arr.EnumerateArray()) list.Add(el.GetInt64());
                return list;
            }

            return type switch
            {
                "Conversation" => new ConversationReceived(
                    JsonSerializer.Deserialize<ConversationDto>(json, Options)!),
                "ConversationAvatar" => new ConversationAvatarReceived(Str("thread_id"), Str("avatar_base64")),
                "Message" => new MessageReceived(
                    JsonSerializer.Deserialize<IncomingMessageDto>(json, Options)!),
                "MessageEdited" => new MessageEditedReceived(
                    Str("thread_id"), Long("target_timestamp"), StrOrNull("new_body"), Long("new_timestamp")),
                "MessageDeleted" => new MessageDeletedReceived(Str("thread_id"), Long("target_timestamp")),
                "Reaction" => new ReactionReceived(
                    Str("thread_id"), Long("target_timestamp"), Str("target_author"), Str("emoji"), Bool("remove")),
                "Typing" => new TypingReceived(Str("thread_id"), Str("sender"), Bool("is_typing")),
                "Receipt" => new ReceiptReceived(Str("sender"), Str("receipt_type"), LongArray("timestamps")),
                "QueueEmpty" => new QueueDrained(),
                "ContactsSynced" => new ContactsSynced(),
                "Other" => new OtherEvent(
                    doc.RootElement.TryGetProperty("description", out var d) ? d.GetString() ?? "" : ""),
                _ => new OtherEvent(json),
            };
        }
        catch (Exception e)
        {
            return new OtherEvent($"parse error: {e.Message}");
        }
    }
}

public sealed record ConversationReceived(ConversationDto Info) : SignalEvent;
public sealed record ConversationAvatarReceived(string ThreadId, string AvatarBase64) : SignalEvent;
public sealed record MessageReceived(IncomingMessageDto Message) : SignalEvent;
public sealed record MessageEditedReceived(string ThreadId, long TargetTimestamp, string? NewBody, long NewTimestamp) : SignalEvent;
public sealed record MessageDeletedReceived(string ThreadId, long TargetTimestamp) : SignalEvent;
public sealed record ReactionReceived(string ThreadId, long TargetTimestamp, string TargetAuthor, string Emoji, bool Remove) : SignalEvent;
public sealed record TypingReceived(string ThreadId, string Sender, bool IsTyping) : SignalEvent;
public sealed record ReceiptReceived(string Sender, string ReceiptType, List<long> Timestamps) : SignalEvent;
public sealed record QueueDrained : SignalEvent;
public sealed record ContactsSynced : SignalEvent;
public sealed record OtherEvent(string Description) : SignalEvent;
